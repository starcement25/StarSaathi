package org.forcepower.starcement.activity.declaration_of_dealer.dataset;

public class MonthDataSet {
    String monthTitle,monthId,isMonthAvailable,monthMessage;

    public String getMonthTitle() {
        return monthTitle;
    }

    public void setMonthTitle(String monthTitle) {
        this.monthTitle = monthTitle;
    }

    public String getMonthId() {
        return monthId;
    }

    public void setMonthId(String monthId) {
        this.monthId = monthId;
    }

    public String getIsMonthAvailable() {
        return isMonthAvailable;
    }

    public void setIsMonthAvailable(String isMonthAvailable) {
        this.isMonthAvailable = isMonthAvailable;
    }

    public String getMonthMessage() {
        return monthMessage;
    }

    public void setMonthMessage(String monthMessage) {
        this.monthMessage = monthMessage;
    }
}
